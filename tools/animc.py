#!/usr/bin/env python3
"""Compile games/<game>/anims.json into animdata.c and anim.h.

Metasprites are 8x8 pieces {dx, dy, tile, attr}. Animations list those
pictures with a duration in frames. Missing file -> empty tables.
"""
import json
import os
import sys


def empty_doc():
    return {'metas': [], 'anims': [], 'defaults': {}}


def load(path):
    if not path or not os.path.isfile(path):
        return empty_doc()
    doc = json.loads(open(path, encoding='utf-8').read())
    base = empty_doc()
    for key in base:
        if key in doc:
            base[key] = doc[key]
    return base


def dump(doc):
    return json.dumps(doc, ensure_ascii=False, indent=2) + '\n'


def new_meta(name='sprite'):
    return {'name': name, 'label': name, 'parts': [{'dx': 0, 'dy': 0, 'tile': 0, 'attr': 0}]}


def new_anim(name='idle'):
    return {'name': name, 'label': name, 'loop': True, 'frames': [{'meta': '', 'dur': 8}]}


def _ident(name):
    out = []
    for ch in name:
        if ch.isalnum() and ord(ch) < 128:
            out.append(ch.upper())
        else:
            out.append('_')
    text = ''.join(out).strip('_') or 'A'
    if text[0].isdigit():
        text = 'A' + text
    return text


def scanline_counts(parts):
    """How many 8x8 pieces cover each scanline. parts are {dy,...}."""
    counts = [0] * 240
    for part in parts:
        dy = int(part.get('dy', 0) or 0)
        for y in range(dy, min(240, dy + 8)):
            if y >= 0:
                counts[y] += 1
    return counts


def frame_warnings(parts):
    errors = []
    if len(parts) > 64:
        errors.append('这一帧有 %d 个精灵（最多 64 个）' % len(parts))
    counts = scanline_counts(parts)
    worst = max(counts) if counts else 0
    if worst > 8:
        y = counts.index(worst)
        errors.append('第 %d 条扫描线叠了 %d 个精灵（最多 8 个）' % (y, worst))
    return errors


def check(doc):
    errors = []
    metas = doc.get('metas', [])
    names = []
    for meta in metas:
        name = meta.get('name', '')
        if not name:
            errors.append('有一个元精灵没有名字')
            continue
        if name in names:
            errors.append('元精灵 %s 重复了' % name)
        names.append(name)
        parts = meta.get('parts') or []
        if not parts:
            errors.append('元精灵 %s 至少要一块图块' % name)
        if len(parts) > 16:
            errors.append('元精灵 %s 超过 16 块' % name)
        for msg in frame_warnings(parts):
            errors.append('元精灵 %s：%s' % (name, msg))
    anims = doc.get('anims', [])
    anames = []
    for anim in anims:
        name = anim.get('name', '')
        if not name:
            errors.append('有一个动画没有名字')
            continue
        if name in anames:
            errors.append('动画 %s 重复了' % name)
        anames.append(name)
        frames = anim.get('frames') or []
        if not frames:
            errors.append('动画 %s 至少要一帧' % name)
        if len(frames) > 16:
            errors.append('动画 %s 超过 16 帧' % name)
        for frame in frames:
            if frame.get('meta') not in names:
                errors.append('动画 %s：未知元精灵 %s' % (name, frame.get('meta') or '（空）'))
            dur = int(frame.get('dur', 1) or 1)
            if not 1 <= dur <= 255:
                errors.append('动画 %s：帧时长要在 1 到 255' % name)
    for ent, anim in (doc.get('defaults') or {}).items():
        if anim not in anames:
            errors.append('实体 %s 的默认动画不存在：%s' % (ent, anim or '（空）'))
    return errors


def emit_sources(doc, types=None):
    errors = check(doc)
    if errors:
        raise SystemExit('\n'.join(errors))
    metas = doc.get('metas', [])
    anims = doc.get('anims', [])
    c = ['/* GENERATED by tools/animc.py */', '#include "engine/engine.h"']
    for i, meta in enumerate(metas):
        parts = []
        for part in meta.get('parts') or []:
            dx = int(part.get('dx', 0) or 0)
            dy = int(part.get('dy', 0) or 0)
            tile = int(part.get('tile', 0) or 0) & 255
            attr = int(part.get('attr', 0) or 0) & 255
            # Stored as signed bytes; tile/attr are read back as unsigned.
            parts += [dx & 255, dy & 255, tile, attr]
        parts.append(128)  # -128 terminator, one byte (dx)
        c.append('static const signed char meta_%d[] = {%s};' % (i, ','.join(str(b if b < 128 else b - 256) for b in parts)))
    if metas:
        c.append('static const signed char *const meta_at[%d] = {%s};' % (
            len(metas), ','.join('meta_%d' % i for i in range(len(metas)))))
    else:
        c.append('static const signed char meta_0[] = {-128};')
        c.append('static const signed char *const meta_at[1] = {meta_0};')
    frame_meta = []
    frame_dur = []
    for i, anim in enumerate(anims):
        mids, durs = [], []
        for frame in anim.get('frames') or []:
            mids.append(str([m.get('name') for m in metas].index(frame.get('meta'))))
            durs.append(str(int(frame.get('dur', 1) or 1) & 255))
        c.append('static const unsigned char afr_%d[] = {%s};' % (i, ','.join(mids)))
        c.append('static const unsigned char adu_%d[] = {%s};' % (i, ','.join(durs)))
        frame_meta.append('afr_%d' % i)
        frame_dur.append('adu_%d' % i)
    if anims:
        c.append('static const unsigned char *const aframes[%d] = {%s};' % (len(anims), ','.join(frame_meta)))
        c.append('static const unsigned char *const adurs[%d] = {%s};' % (len(anims), ','.join(frame_dur)))
        c.append('static const unsigned char alen[%d] = {%s};' % (
            len(anims), ','.join(str(len(a.get('frames') or [])) for a in anims)))
        c.append('static const unsigned char aloop[%d] = {%s};' % (
            len(anims), ','.join('1' if a.get('loop', True) else '0' for a in anims)))
    else:
        c.append('static const unsigned char afr_0[] = {0};')
        c.append('static const unsigned char adu_0[] = {1};')
        c.append('static const unsigned char *const aframes[1] = {afr_0};')
        c.append('static const unsigned char *const adurs[1] = {adu_0};')
        c.append('static const unsigned char alen[1] = {1};')
        c.append('static const unsigned char aloop[1] = {0};')
    c.append('const unsigned char anim_total = %d;' % len(anims))
    c.append('const unsigned char anim_metas = %d;' % len(metas))
    c.append('''
unsigned char anim_length(unsigned char id){ if(id >= anim_total) return 0; return alen[id]; }
unsigned char anim_looping(unsigned char id){ if(id >= anim_total) return 0; return aloop[id]; }
unsigned char anim_step(unsigned char id, unsigned char frame){
  if(id >= anim_total || frame >= alen[id]) return 1;
  return adurs[id][frame];
}
const signed char *anim_picture(unsigned char id, unsigned char frame){
  unsigned char mid;
  if(id >= anim_total || frame >= alen[id]) return 0;
  mid = aframes[id][frame];
  if(mid >= anim_metas) return 0;
  return meta_at[mid];
}
''')
    defaults = doc.get('defaults') or {}
    anim_names = [a.get('name') for a in anims]
    fn = ['unsigned char anim_for_type(unsigned char type){']
    matched = False
    for ent, anim in defaults.items():
        if types and ent in types and anim in anim_names:
            fn.append('  if(type == %d) return %d;' % (types[ent], anim_names.index(anim)))
            matched = True
    if not matched:
        fn.append('  (void)type;')
    fn.append('  return 255;')
    fn.append('}')
    c.append('\n'.join(fn))
    h = ['/* GENERATED by tools/animc.py */', '#ifndef ANIM_H', '#define ANIM_H',
         '#define ANIM_NONE 255']
    for i, anim in enumerate(anims):
        h.append('#define ANIM_%s %d' % (_ident(anim.get('name', 'A%d' % i)), i))
    h.append('#endif')
    return '\n'.join(c) + '\n', '\n'.join(h) + '\n'


def _types(game_dir):
    path = os.path.join(game_dir, 'entities.txt')
    if not os.path.isfile(path):
        return {}
    here = os.path.dirname(os.path.abspath(__file__))
    if here not in sys.path:
        sys.path.insert(0, here)
    import ent2c
    spec = ent2c.load_types(path)
    return {t.name: t.id for t in spec.types}


def write(game_dir, out_dir):
    doc = load(os.path.join(game_dir, 'anims.json'))
    c_text, h_text = emit_sources(doc, _types(game_dir))
    open(os.path.join(out_dir, 'animdata.c'), 'w').write(c_text)
    open(os.path.join(out_dir, 'anim.h'), 'w').write(h_text)


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit('usage: animc.py games/<game> build/<game>/gen')
    write(sys.argv[1], sys.argv[2])
