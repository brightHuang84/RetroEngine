#!/usr/bin/env python3
"""One-time helper that DREW the example tiles.png sheets (font + game tiles).
After that the PNGs are the source of truth: edit them in any paint program
(use only black / 85 grey / 170 grey / white). usage: make_sheets.py <game> <out.png>"""
import sys
from PIL import Image
G={'0':0x7B6F,'1':0x2C97,'2':0x73E7,'3':0x73CF,'4':0x5BC9,'5':0x79CF,'6':0x79EF,'7':0x7249,
'8':0x7BEF,'9':0x7BCF,'A':0x2BED,'B':0x6BAE,'C':0x7927,'D':0x6B6E,'E':0x79E7,'F':0x79E4,
'G':0x796F,'H':0x5BED,'I':0x7497,'J':0x1B6F,'K':0x5BAD,'L':0x4927,'M':0x5FED,'N':0x6B6D,'O':0x7B6F,
'P':0x7BE4,'Q':0x7B79,'R':0x7BF5,'S':0x79CF,'T':0x7492,'U':0x5B6F,'V':0x5B6A,'W':0x5BFD,'X':0x5AAD,'Y':0x5A92,'Z':0x72A7,
':':0x0410,'!':0x2482,'-':0x01C0,'.':0x0002,'/':0x12A4}
LV=[0,85,170,255]
def put(im, t, rows):
    tx, ty = (t % 16) * 8, (t // 16) * 8
    for y, r in enumerate(rows):
        for x, c in enumerate(r): im.putpixel((tx + x, ty + y), LV[int(c)])
def font(im, color='3'):
    m = [0, 0, 1, 2, 3, 4, 4]
    for ch, g in G.items():
        rows = []
        for y in range(8):
            s = ''
            for x in range(8):
                on = y < 7 and x < 6 and g & (1 << (14 - (m[y] * 3 + x // 2)))
                s += color if on else '0'
            rows.append(s)
        put(im, ord(ch), rows)
def breakout(im):
    put(im,0x80,['22222222','21111111','21111111','21111111','21111111','21111111','23333333','00000000'])
    put(im,0x81,['22222220','11111130','11111130','11111130','11111130','11111130','33333330','00000000'])
    put(im,0x82,['12211221','21122112','12211221','21122112','12211221','21122112','12211221','21122112'])
    put(im,0x90,['00000000','00111100','01222210','01222210','01222210','01222210','00111100','00000000'])
    put(im,0x91,['11111111','12222222','12222222','33333333','00000000','00000000','00000000','00000000'])
    put(im,0x92,['11111111','22222222','22222222','33333333','00000000','00000000','00000000','00000000'])
    put(im,0x93,['11111111','22222221','22222221','33333333','00000000','00000000','00000000','00000000'])
def platformer(im):
    put(im,0x80,['33333333','32323232','11111111','12111211','11111111','11211121','11111111','11111111'])  # grass top ground
    put(im,0x81,['11111111','12111211','11111111','11211121','11111111','12111211','11111111','11211121'])  # dirt
    put(im,0x82,['33333333','32222223','32222223','31111113','11111111','00000000','00000000','00000000'])  # platform
    put(im,0x83,['00000000','00033000','00333300','03333330','33333333','03333330','00000000','00000000'])  # cloud
    put(im,0x84,['00000000','00000000','00000000','00222000','02222200','22122220','21222122','22222222'])  # bush
    put(im,0x85,['33333333','31111112','31111112','31111112','31111112','31111112','31111112','22222222'])  # block
    # player (2 tiles tall): head, body frames
    put(im,0xA0,['00111100','01111110','01133130','01333330','00333300','00011000','01122110','11222211'])
    put(im,0xA1,['11222211','01222210','00222200','00111100','00100100','00100100','01100110','00000000'])
    put(im,0xA2,['11222211','01222210','00222200','00111100','01100010','11000011','10000001','00000000'])
    put(im,0xB0,['00011000','00122100','01233210','01232210','01232210','01222210','00122100','00011000'])  # coin
    put(im,0xB8,['00000000','00111100','01111110','13311331','11111111','01111110','01100110','11000011'])  # enemy
def main(game, out):
    im = Image.new('L', (128, 128), 0)
    font(im); {'breakout': breakout, 'platformer': platformer}[game](im)
    im.save(out)
if __name__ == '__main__': main(*sys.argv[1:3])
