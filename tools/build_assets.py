#!/usr/bin/env python3
"""Build all assets of one game: games/<g>/tiles.png -> game.chr + chr_tiles C array,
games/<g>/maps/order.txt -> column-RLE level table in maps.c.
usage: build_assets.py games/<g> build/<g>/gen [mmc5|nrom]"""
import sys, os, subprocess
src, out = sys.argv[1], sys.argv[2]
mapper = sys.argv[3] if len(sys.argv) > 3 else 'mmc5'
if mapper not in ('mmc5', 'nrom'):
    sys.exit('mapper must be mmc5 or nrom')
os.makedirs(out, exist_ok=True)
here = os.path.dirname(os.path.abspath(__file__))
if here not in sys.path:
    sys.path.insert(0, here)
import nes_target
_mapper_file, exattr = nes_target.read(src)
if mapper != 'mmc5':
    exattr = False

def write_palette(src, out):
    path = os.path.join(src, 'palette.txt')
    if not os.path.exists(path):
        sys.exit('missing %s (32 NES color indices)' % path)
    vals = []
    for line in open(path):
        line = line.split('#', 1)[0]
        for tok in line.split():
            vals.append(int(tok, 16) & 63)
    if len(vals) != 32:
        sys.exit('%s: expected 32 colors, got %d' % (path, len(vals)))
    lines = ['/* GENERATED from palette.txt by tools/build_assets.py */',
             'const unsigned char game_palette[32] = {']
    for i in range(0, 32, 8):
        lines.append('  ' + ','.join('0x%02X' % v for v in vals[i:i + 8]) + ',')
    lines.append('};')
    open(os.path.join(out, 'palette.c'), 'w').write('\n'.join(lines) + '\n')
subprocess.check_call([sys.executable, os.path.join(here, 'png2chr.py'), os.path.join(src, 'tiles.png'),
                       os.path.join(out, 'game.chr'), os.path.join(out, 'tiles.c'), mapper])
subprocess.check_call([sys.executable, os.path.join(here, 'png2gba.py'), os.path.join(src, 'tiles.png'),
                       os.path.join(out, 'tiles_gba.c')])
write_palette(src, out)
h = ['/* GENERATED by tools/build_assets.py */', '#ifndef ASSETS_H', '#define ASSETS_H',
     'extern const unsigned char game_palette[32];']
code = subprocess.check_output([sys.executable, os.path.join(here, 'mappack.py'), src, mapper]).decode()
open(os.path.join(out, 'maps.c'), 'w').write(code)
for line in code.splitlines():
    if line.startswith('#define ENT_') or (line.startswith('#define MAP_') and '_ENT_N ' in line):
        h.append(line)
h.append('#endif')
open(os.path.join(out, 'assets.h'), 'w').write('\n'.join(h) + '\n')
print('assets ->', out)
