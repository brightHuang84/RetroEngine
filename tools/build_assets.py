#!/usr/bin/env python3
"""Build all assets of one game: games/<g>/tiles.png -> game.chr + chr_tiles C array,
every games/<g>/*.txt|*.csv map -> map_<name>[], map_<name>_attr[], map_<name>_flags[].
usage: build_assets.py games/<g> build/<g>/gen"""
import sys, os, glob, subprocess
src, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
here = os.path.dirname(os.path.abspath(__file__))
subprocess.check_call([sys.executable, os.path.join(here, 'png2chr.py'), os.path.join(src, 'tiles.png'),
                       os.path.join(out, 'game.chr'), os.path.join(out, 'tiles.c')])
subprocess.check_call([sys.executable, os.path.join(here, 'png2gba.py'), os.path.join(src, 'tiles.png'),
                       os.path.join(out, 'tiles_gba.c')])
maps = sorted(glob.glob(os.path.join(src, '*.txt')) + glob.glob(os.path.join(src, '*.csv')))
maps = [m for m in maps if os.path.basename(m).lower() != 'songs.txt']
h = ['/* GENERATED by tools/build_assets.py */', '#ifndef ASSETS_H', '#define ASSETS_H']
with open(os.path.join(out, 'maps.c'), 'w') as f:
    for m in maps:
        name = os.path.splitext(os.path.basename(m))[0]
        code = subprocess.check_output([sys.executable, os.path.join(here, 'map2c.py'), m, name]).decode()
        f.write(code + '\n')
        for line in code.splitlines():
            if line.startswith('#define'): h.append(line)
        h += ['extern const unsigned char map_%s[];' % name, 'extern const unsigned char map_%s_attr[];' % name,
              'extern const unsigned char map_%s_flags[];' % name]
h.append('#endif')
open(os.path.join(out, 'assets.h'), 'w').write('\n'.join(h) + '\n')
print('assets ->', out)
